"""Single source of truth for the Bulalakaw palette (FD-01).
Writes: assets/palette.png (reference sheet), assets/palette.gpl (Aseprite/Krita/GIMP),
assets/palette.hex (Lospec/Pixelorama), scripts/Palette.gd (Godot constants)."""
import sys
from PIL import Image, ImageDraw, ImageFont

OUT = sys.argv[1]
GROUPS = [
    ("Mars environment", "Ground, rocks, dust, outside", [
        ("mars_sand", "FCA54A", "light ground, dust"), ("mars_orange", "FF6D00", "main ground"),
        ("mars_rust", "FD5100", "ground shadow"), ("mars_crimson", "C3002B", "rocks, deep shadow")]),
    ("Modules, desk UI, buildings", "Habitat, panels, plots, cards", [
        ("base_cream", "EEDBC8", "module white, card fill"), ("base_stone", "CBB7B3", "panel light"),
        ("base_mauve", "9B828B", "panel mid, shading"), ("base_plum", "684266", "panel dark, desk")]),
    ("Sky and monitors", "Night sky, screens, glow", [
        ("sky_haze", "86BDC8", "screen glow, day haze"), ("sky_indigo", "5148AB", "monitor screen"),
        ("sky_violet", "5E018B", "night sky"), ("sky_night", "552465", "deep night, monitor off")]),
    ("Crew suit colours", "Main + shade (C1-C4)", [
        ("crew_lani", "EF5DC0", "C1 main"), ("crew_lani_shade", "B01081", "C1 shade"),
        ("crew_maya", "A2E69F", "C2 main"), ("crew_maya_shade", "57BE6B", "C2 shade"),
        ("crew_mateo", "FF8696", "C3 main"), ("crew_mateo_shade", "D8305B", "C3 shade"),
        ("crew_carlo", "A2E747", "C4 main"), ("crew_carlo_shade", "6FC60C", "C4 shade")]),
    ("Buttons, status, alerts", "Main + shade", [
        ("status_warn", "FEE400", "warning"), ("status_warn_shade", "CAA836", "warning shade"),
        ("status_danger", "EC0500", "danger"), ("status_danger_shade", "B03228", "danger shade"),
        ("status_ok", "38A918", "OK, safe"), ("status_ok_shade", "44721C", "OK shade")]),
    ("Added in remaster", "Needed for outlines and text", [
        ("ink", "2B1A2E", "outlines, text on light"), ("highlight", "FFF6EC", "shine, text on dark")]),
]

def rgb(h): return tuple(int(h[i:i+2], 16) for i in (0, 2, 4))

# ---- palette.gpl / palette.hex ----
with open(f"{OUT}/assets/palette.gpl", "w") as f:
    f.write("GIMP Palette\nName: Bulalakaw Station\nColumns: 4\n#\n")
    for _, _, cols in GROUPS:
        for name, hx, _ in cols:
            r, g, b = rgb(hx); f.write(f"{r:3d} {g:3d} {b:3d}\t{name}\n")
with open(f"{OUT}/assets/palette.hex", "w") as f:
    for _, _, cols in GROUPS:
        for _, hx, _ in cols: f.write(hx.lower() + "\n")

# ---- Palette.gd ----
lines = ["class_name Palette", "extends RefCounted",
         "## Bulalakaw colour palette (FD-01). Generated by tools/make_palette.py: edit there, not here.", ""]
for title, _, cols in GROUPS:
    lines.append(f"# {title}")
    for name, hx, use in cols:
        lines.append(f'const {name.upper()} := Color("#{hx}")  # {use}')
    lines.append("")
with open(f"{OUT}/scripts/Palette.gd", "w") as f: f.write("\n".join(lines))

# ---- palette.png reference sheet ----
W, H = 1280, 1400
ink, cream = rgb("2B1A2E"), rgb("FFF6EC")
img = Image.new("RGB", (W, H), cream); d = ImageDraw.Draw(img)
F = "/usr/share/fonts/truetype/dejavu/"
ft = ImageFont.truetype(F + "DejaVuSans-Bold.ttf", 34); fh = ImageFont.truetype(F + "DejaVuSans-Bold.ttf", 20)
fs = ImageFont.truetype(F + "DejaVuSans.ttf", 14); fm = ImageFont.truetype(F + "DejaVuSansMono.ttf", 13)
d.text((40, 28), "Bulalakaw Station — colour palette (FD-01)", font=ft, fill=ink)
d.text((40, 72), "Use only these colours. Crew mapping C1–C4 is provisional. Every alert also needs its own shape (red/green look alike to colourblind players).", font=fs, fill=rgb("684266"))
y = 112
for title, sub, cols in GROUPS:
    d.text((40, y), title, font=fh, fill=ink); d.text((40 + d.textlength(title, font=fh) + 12, y + 5), sub, font=fs, fill=rgb("9B828B"))
    y += 32
    n = len(cols); sw = min(140, (W - 80 - (n - 1) * 20) // n)
    for i, (name, hx, use) in enumerate(cols):
        x = 40 + i * (sw + 20)
        d.rounded_rectangle((x, y, x + sw, y + 62), radius=12, fill=rgb(hx), outline=ink, width=2)
        d.text((x, y + 68), name, font=fm, fill=ink)
        d.text((x, y + 86), "#" + hx, font=fm, fill=rgb("684266"))
    y += 122
img = img.crop((0, 0, W, y + 4))
img.save(f"{OUT}/assets/palette.png")

# ---- contrast check for text pairs (WCAG ratio, >= 4.5 good for text) ----
def L(h):
    def c(v):
        v /= 255; return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b = rgb(h); return 0.2126 * c(r) + 0.7152 * c(g) + 0.0722 * c(b)
def ratio(a, b):
    la, lb = sorted([L(a), L(b)], reverse=True); return (la + 0.05) / (lb + 0.05)
for fg, bg, label in [("2B1A2E", "EEDBC8", "ink on cream card"), ("FFF6EC", "684266", "highlight on plum panel"),
                      ("FFF6EC", "5148AB", "highlight on monitor"), ("2B1A2E", "FEE400", "ink on warning"),
                      ("FFF6EC", "EC0500", "highlight on danger"), ("2B1A2E", "FCA54A", "ink on mars sand")]:
    print(f"{label:28s} {ratio(fg, bg):5.1f}:1")
print("written:", img.size)
